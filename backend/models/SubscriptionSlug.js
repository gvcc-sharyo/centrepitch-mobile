import mongoose from "mongoose";

const subscriptionSlugSchema = new mongoose.Schema(
  {
    slug: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      lowercase: true,
    },
    label: {
      type: String,
      required: true,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
    sortOrder: {
      type: Number,
      default: 0,
      index: true,
    },
    createdBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    updatedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
  },
  {
    timestamps: true,
    collection: "subscriptionslugs",
  }
);

subscriptionSlugSchema.index({ isActive: 1, sortOrder: 1, label: 1 });

const SubscriptionSlug = mongoose.model("SubscriptionSlug", subscriptionSlugSchema);

export default SubscriptionSlug;

